#!/usr/bin/env python3
"""Caddy config for one selo site, made from the site's own hugo.toml (Python 3.11+, no extra packages).

  python3 caddy_site.py <site repo> <web root>   -> prints the config block

What the block does (the same as rakovac.rs's deploy/Caddyfile):
  - HTTPS for the domain in baseURL (Caddy gets and renews the certificate), www -> bare domain
  - "/" sends the visitor to their language: sr-Latn -> /sr/, sr / sr-Cyrl / sr-RS -> /cyr/,
    hr / bs / sh / cnr / me -> /hr/ (or /sr/ when the site has no Croatian), ru / uk / be -> /ru/, else /en/
    (only languages the site has switched on)
  - /weather.json: current weather for the site's map centre (or params.weatherPoint) from Open-Meteo,
    fetched by the server, so visitors' browsers never contact a third party
  - caching headers and a 404 page in the visitor's language
Nothing here is site-specific by hand: a new site gets its config from its hugo.toml."""
import sys, tomllib
from urllib.parse import urlparse

repo, root = sys.argv[1], sys.argv[2]
cfg = tomllib.load(open(f'{repo}/hugo.toml', 'rb'))
host = urlparse(cfg['baseURL']).hostname
off = set(cfg.get('disableLanguages', []))
langs = [l for l, _ in sorted(cfg.get('languages', {}).items(), key=lambda kv: kv[1].get('weight', 99)) if l not in off]
default = 'en' if 'en' in langs else cfg.get('defaultContentLanguage', langs[0])
p = cfg.get('params', {})
lat, lon = p.get('weatherPoint') or p.get('mapCenter') or [44.8, 20.46]


def pick(*cands):
    for c in cands:
        if c in langs:
            return c
    return default


rules = [('~^sr-Latn', pick('sr', 'hr')), (r'~^sr\b', pick('cyr', 'sr')),
         (r'~^(hr|bs|sh|cnr|me)\b', pick('hr', 'sr')), (r'~^(ru|uk|be)\b', pick('ru')),
         (r'~^de\b', pick('de')), (r'~^hu\b', pick('hu'))]
mp = '\n'.join(f'\t\t{a} {b}' for a, b in rules) + f'\n\t\tdefault {default}'
e404 = '\n'.join(f'\t\t@{l} path /{l}/*\n\t\thandle @{l} {{\n\t\t\trewrite * /{l}/404.html\n\t\t}}' for l in langs if l != default)

print(f'''# {host}: generated by the selo engine (hosting/caddy_site.py) from the site's hugo.toml. Do not edit here.
{host} {{
	root * {root}
	encode zstd gzip

	@home path /
	map {{header.Accept-Language}} {{lang}} {{
{mp}
	}}
	handle @home {{
		header Vary Accept-Language
		redir * /{{lang}}/ 302
	}}
	handle /weather.json {{
		rewrite * /v1/forecast?latitude={lat}&longitude={lon}&current=temperature_2m,apparent_temperature,is_day,precipitation,weather_code,wind_speed_10m,wind_gusts_10m&timezone=Europe%2FBelgrade&wind_speed_unit=kmh
		reverse_proxy https://api.open-meteo.com {{
			header_up Host {{upstream_hostport}}
			header_up -X-Forwarded-For
			header_up -X-Forwarded-Host
			header_up -X-Forwarded-Proto
			header_up -X-Real-IP
			header_up -Cookie
			header_up -Referer
			header_up -Origin
			header_up User-Agent "{host} weather"
			header_down -Set-Cookie
			header_down -Access-Control-Allow-Origin
			header_down Cache-Control "public, max-age=600"
			transport http {{
				dial_timeout 3s
				response_header_timeout 5s
			}}
		}}
	}}
	handle {{
		file_server
	}}

	header {{
		Strict-Transport-Security "max-age=31536000"
		X-Content-Type-Options "nosniff"
		Referrer-Policy "strict-origin-when-cross-origin"
		-Server
	}}
	@html path / *.html */
	header @html Cache-Control "no-cache"
	header /version.txt Cache-Control "no-store"
	header /css/* Cache-Control "public, max-age=31536000, immutable"
	header /js/* Cache-Control "public, max-age=31536000, immutable"
	header /pagefind/* Cache-Control "public, max-age=600"
	@assets path /img/* /video/* /fonts/* /downloads/* /vendor/* /favicon* /apple-touch-icon.png /icon-*.png
	header @assets Cache-Control "public, max-age=604800"

	handle_errors 404 {{
{e404}
		handle {{
			rewrite * /{default}/404.html
		}}
		file_server
	}}
}}

www.{host} {{
	redir https://{host}{{uri}} permanent
}}''')
